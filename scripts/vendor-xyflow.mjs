// Pre-bundles @xyflow/react (and zustand, d3, …) into src/vendor/xyflow-react.js with React left external.
//
// Lens hands the extension's own bundle its React, but a package required from node_modules resolves
// "react" there, a second copy whose hooks have no renderer ("Cannot read properties of null (reading
// 'useState')"). Bundled into our source, every require("react") comes from dist/index.js and gets Lens's.
// Run `npm run vendor` after upgrading @xyflow/react.
import { build } from "esbuild";
import { copyFileSync } from "node:fs";

await build({
  entryPoints: ["@xyflow/react"],
  bundle: true,
  format: "cjs",
  platform: "browser",
  target: "es2020",
  outfile: "src/vendor/xyflow-react.js",
  external: ["react", "react-dom", "react/jsx-runtime"],
  legalComments: "inline",
  banner: { js: "/* eslint-disable */\n// Generated by scripts/vendor-xyflow.mjs from @xyflow/react (MIT). Do not edit.\n" },
});

copyFileSync("node_modules/@xyflow/react/dist/style.css", "src/vendor/xyflow-react.css");
console.log("Vendored @xyflow/react into src/vendor/");
